import { spawnSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { basename } from "node:path";

const DEFAULT_EXPECTED_PRODUCTION_ORIGIN = "https://kobitokey-studio.s-hiraoku.workers.dev";
const expectedProductionOrigin =
  process.env.BROWSER_FIRMWARE_EXPECTED_PRODUCTION_ORIGIN?.trim() || DEFAULT_EXPECTED_PRODUCTION_ORIGIN;
const args = process.argv.slice(2);

if (args.includes("--help") || args.includes("-h")) {
  console.log(`Usage: node scripts/check-browser-firmware-public-release.mjs --e2e-report <report.json> [production-url]

Runs the final browser Firmware Mode public release gate:
  1. external E2E evidence validation
  2. merge readiness against origin/main
  3. production release preflight with GitHub OAuth client id

Required:
  --e2e-report <report.json>
    External E2E evidence generated by collect:browser-firmware:e2e-report.
  BROWSER_FIRMWARE_PREFLIGHT_OAUTH_CLIENT_ID
    Public GitHub OAuth App client id embedded in the production frontend.
  BROWSER_FIRMWARE_EXPECTED_PRODUCTION_ORIGIN
    Optional override for the public production origin. Defaults to
    ${DEFAULT_EXPECTED_PRODUCTION_ORIGIN}.
  BROWSER_FIRMWARE_RELEASE_SKIP_REASON
    Required when using --skip-merge-readiness or --skip-current-head.

Optional:
  production-url
    Defaults to BROWSER_FIRMWARE_PRODUCTION_URL or production.url in the E2E report.
    If provided, it must match the E2E report production.url.
  --skip-merge-readiness
    Use only if checking a deployed commit that is no longer the current branch.
  --skip-current-head
    Use only if the E2E report intentionally targets an app deployment that is
    not the current git HEAD.`);
  process.exit(0);
}

const e2eReportPath = readOption("--e2e-report") || process.env.BROWSER_FIRMWARE_E2E_REPORT;
const requestedProductionUrl = args.find((arg, index) => {
  if (arg.startsWith("--")) return false;
  return args[index - 1] !== "--e2e-report";
});
const skipMergeReadiness = args.includes("--skip-merge-readiness");
const skipCurrentHead = args.includes("--skip-current-head");
const skipReason = process.env.BROWSER_FIRMWARE_RELEASE_SKIP_REASON?.trim() || "";
const issues = [];
let report;
let reportAppCommitSha = "";

if (!process.env.BROWSER_FIRMWARE_PREFLIGHT_OAUTH_CLIENT_ID?.trim()) {
  issues.push("BROWSER_FIRMWARE_PREFLIGHT_OAUTH_CLIENT_ID is required for the production OAuth release preflight");
}
if ((skipMergeReadiness || skipCurrentHead) && !skipReason) {
  issues.push("BROWSER_FIRMWARE_RELEASE_SKIP_REASON is required when using public-release skip flags");
}
if (!e2eReportPath) {
  issues.push("--e2e-report <report.json> or BROWSER_FIRMWARE_E2E_REPORT is required");
} else if (!existsSync(e2eReportPath)) {
  issues.push(`${e2eReportPath} does not exist`);
} else {
  try {
    report = JSON.parse(readFileSync(e2eReportPath, "utf8"));
  } catch (error) {
    issues.push(`${e2eReportPath} could not be parsed as JSON: ${formatError(error)}`);
  }
}

const reportProductionUrl = typeof report?.production?.url === "string" ? report.production.url.trim() : "";
const envProductionUrl = process.env.BROWSER_FIRMWARE_PRODUCTION_URL?.trim() || "";
const preflightProductionUrl = requestedProductionUrl || envProductionUrl || reportProductionUrl;

if (report && !reportProductionUrl) {
  issues.push("e2e report production.url is required so the production preflight checks the same deployed URL");
}
if (!preflightProductionUrl) {
  issues.push("production URL is required via positional argument, BROWSER_FIRMWARE_PRODUCTION_URL, or e2e report production.url");
}
if (reportProductionUrl && requestedProductionUrl && !sameUrl(reportProductionUrl, requestedProductionUrl)) {
  issues.push("production-url argument must match e2e report production.url");
}
if (reportProductionUrl && envProductionUrl && !sameUrl(reportProductionUrl, envProductionUrl)) {
  issues.push("BROWSER_FIRMWARE_PRODUCTION_URL must match e2e report production.url");
}
if (reportProductionUrl && !sameOrigin(reportProductionUrl, expectedProductionOrigin)) {
  issues.push("e2e report production.url must use the expected public production origin");
}
if (preflightProductionUrl && !sameOrigin(preflightProductionUrl, expectedProductionOrigin)) {
  issues.push("production preflight URL must use the expected public production origin");
}
if (report && !skipCurrentHead) {
  reportAppCommitSha = typeof report.ci?.appCommitSha === "string" ? report.ci.appCommitSha.trim() : "";
  const currentHeadSha = readGitHeadSha();
  if (!reportAppCommitSha) {
    issues.push("e2e report ci.appCommitSha is required so public-release can prove the current app commit");
  } else if (!currentHeadSha) {
    issues.push("current git HEAD could not be read; use --skip-current-head only when checking a deployed commit intentionally");
  } else if (reportAppCommitSha !== currentHeadSha) {
    issues.push("e2e report ci.appCommitSha must match the current git HEAD");
  }
} else if (report) {
  reportAppCommitSha = typeof report.ci?.appCommitSha === "string" ? report.ci.appCommitSha.trim() : "";
}

if (issues.length > 0) {
  console.error("Browser firmware public release is not ready:");
  for (const issue of issues) {
    console.error(`- ${issue}`);
  }
  process.exit(1);
}

run(process.execPath, ["scripts/check-browser-firmware-external-evidence.mjs", e2eReportPath]);
if (!skipMergeReadiness) {
  run(process.execPath, ["scripts/check-browser-firmware-merge-readiness.mjs"]);
}
run(process.execPath, [
  "scripts/check-browser-firmware-production-preflight.mjs",
  "--require-oauth",
  preflightProductionUrl,
], reportAppCommitSha ? { BROWSER_FIRMWARE_PREFLIGHT_APP_COMMIT_SHA: reportAppCommitSha } : {});

console.log(`OK ${basename(e2eReportPath)} passed browser firmware public release gate`);

function readOption(name) {
  const index = args.indexOf(name);
  if (index === -1) {
    return undefined;
  }
  return args[index + 1] && !args[index + 1].startsWith("--") ? args[index + 1] : undefined;
}

function sameUrl(left, right) {
  try {
    return new URL(left).href === new URL(right).href;
  } catch {
    return left === right;
  }
}

function sameOrigin(left, right) {
  try {
    return new URL(left).origin === new URL(right).origin;
  } catch {
    return left === right;
  }
}

function formatError(error) {
  return error instanceof Error ? error.message : String(error);
}

function readGitHeadSha() {
  const result = spawnSync("git", ["rev-parse", "HEAD"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  return result.status === 0 ? result.stdout.trim() : "";
}

function run(command, commandArgs, extraEnv = {}) {
  const result = spawnSync(command, commandArgs, {
    env: { ...process.env, ...extraEnv },
    stdio: "inherit",
  });
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}
